def _haversine(lat1, lon1, lat2, lon2) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = p2 - p1
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(min(1.0, math.sqrt(a)))


def nearest_city(lat: float, lon: float, max_km: float = 60.0):
    """GPS -> 最近城市名。

    注意：内置的是"城市中心点"，最多只能给到地级市一级。
    距离阈值压到 60km，避免把上高（宜春）这种县级地方
    算成 100 多公里外的南昌。
    """
    try:
        lat, lon = float(lat), float(lon)
    except Exception:
        return None
    best, best_d = None, 1e18
    for name, clat, clon in CITIES:
        d = _haversine(lat, lon, clat, clon)
        if d < best_d:
            best, best_d = name, d
    if best and best_d <= max_km:
        return best
    return None


def nearest_city_wide(lat: float, lon: float):
    """放宽到全国最近的省级城市，仅当严格匹配失败时兜底。"""
    try:
        lat, lon = float(lat), float(lon)
    except Exception:
        return None, None
    if not (17.0 <= lat <= 54.5 and 73.0 <= lon <= 135.5):
        return None, None
    best, best_d = None, 1e18
    for name, clat, clon in CITIES:
        d = _haversine(lat, lon, clat, clon)
        if d < best_d:
            best, best_d = name, d
    if best:
        return best, best_d
    return None, None


def _region_of_city(city: str):
    """城市 -> 省份/地区名，用于"城市没命中但能给出大概地区"的场景。"""
    return PROVINCE_OF_CITY.get(city) or city


def city_detail(lat, lon, max_km: float = 60.0):
    """GPS -> (县市名, 所属地级市/省, 距离km)。用于地点页做"省市 / 县市"两级展示。"""
    try:
        lat, lon = float(lat), float(lon)
    except Exception:
        return None, None, None
    best, best_d = None, 1e18
    for name, clat, clon in CITIES:
        d = _haversine(lat, lon, clat, clon)
        if d < best_d:
            best, best_d = name, d
    if best is None:
        return None, None, None
    if best_d <= max_km:
        return best, _region_of_city(best), round(best_d, 1)
    # 超范围：仍给最近的，但标记为"约"
    return best, _region_of_city(best), round(best_d, 1)


def place_parts(place: str):
    """把地点名拆成 (上级地区, 本级)。

    例如「上高」->（「江西」，「上高」），「北京」->（「」，「北京」）。
    地点页据此按 省份/地区 -> 县市 两级折叠展示。
    """
    if not place or place == UNKNOWN:
        return ("", UNKNOWN)
    parent = PROVINCE_OF_CITY.get(place, "")
    if parent and parent != place:
        return (parent, place)
    return ("", place)


def coord_label(lat: float, lon: float) -> str:
    """没有匹配到城市时，用坐标网格作为地点名（同一区域会聚到一起）。"""
    try:
        lat = float(lat); lon = float(lon)
    except Exception:
        return UNKNOWN
    ns = "北纬" if lat >= 0 else "南纬"
    ew = "东经" if lon >= 0 else "西经"
    return "%s%.1f° %s%.1f°" % (ns, abs(lat), ew, abs(lon))


def place_from_text(text: str):
    """从路径/文件名里找地点线索。"""
    if not text:
        return None
    s = _NOISE.sub(" ", text)
    for name in _ALL_NAMES:
        if name in s:
            return name
    return None


def resolve_place(lat, lon, path_hint: str = "") -> str:
    """综合三条线索给出地点名，永远返回一个可分组的值。

    优先级：目录/文件名里的地名 > GPS 最近城市(60km) > GPS 最近城市(全国)
            > 「未知地点」
    不再显示经纬度字符串——那种名字对用户没有任何意义。
    """
    named = place_from_text(path_hint)
    if named:
        return named

    if lat is not None and lon is not None:
        city = nearest_city(lat, lon, max_km=60.0)
        if city:
            return city
        city, dist = nearest_city_wide(lat, lon)
        if city:
            return city

    return UNKNOWN


def describe_coord(lat, lon) -> str:
    """把坐标翻译成人能读的地区名（用于详情页显示原始定位）。"""
    if lat is None or lon is None:
        return ""
    city = nearest_city(lat, lon, max_km=120.0) or nearest_city_wide(lat, lon)
    if city:
        return "%s（%s）" % (city, _region_of_city(city))
    return coord_label(lat, lon)


def place_from_folder(path: str) -> str:
    """只看目录部分（文件名里的"北京"更可能是内容而非地点）。"""
    return place_from_text(os.path.dirname(path or "")) or UNKNOWN
