    fn gps_resolves_to_nearest_city() {
        // 天安门附近
        assert_eq!(resolve_place(Some(39.9087), Some(116.3975), ""), "北京");
        // 外滩
        assert_eq!(resolve_place(Some(31.2397), Some(121.4900), ""), "上海");
    }

    #[test]
    fn gps_within_60km_only() {
        // 距北京约 100km 处，60km 严格匹配失败，但全国兜底仍给最近城市
        let p = resolve_place(Some(40.80), Some(116.41), "");
        assert_eq!(p, "北京");
    }

    #[test]
    fn county_level_city_resolved() {
        // 上高（宜春），县级点位的距离阈值得压到 60km 内
        let p = resolve_place(Some(28.24), Some(114.92), "");
        assert_eq!(p, "上高");
        assert_eq!(region_of_city("上高"), "江西");
    }

