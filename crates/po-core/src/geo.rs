fn noise_re() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        Regex::new(
            r"(?i)(截图|屏幕|screenshot|screen shot|微信|qq|image|img|dsc|dcim|备份|backup|临时|temp|新建文件夹|未命名)",
        )
        .unwrap()
    })
}

/// 所有地名，按长度降序（长的优先匹配，避免「吉林」吃掉「吉林市」）。
fn all_names() -> &'static Vec<&'static str> {
    static NAMES: OnceLock<Vec<&'static str>> = OnceLock::new();
    NAMES.get_or_init(|| {
        let mut v: Vec<&str> = CITIES.iter().map(|(n, _, _)| *n).collect();
        v.extend_from_slice(REGIONS);
        v.sort_by(|a, b| b.chars().count().cmp(&a.chars().count()));
        v.dedup();
        v
    })
}

/// GPS -> 最近城市名。返回 `(城市, 距离 km)`。
pub fn nearest_city(lat: f64, lon: f64, max_km: f64) -> Option<(&'static str, f64)> {
    if !(lat.is_finite() && lon.is_finite()) {
        return None;
    }
    let mut best: Option<(&'static str, f64)> = None;
    for (name, clat, clon) in CITIES {
        let d = haversine_km(lat, lon, *clat, *clon);
        if best.map(|(_, bd)| d < bd).unwrap_or(true) {
            best = Some((name, d));
        }
    }
    match best {
        Some((n, d)) if d <= max_km => Some((n, d)),
        _ => None,
    }
}

/// 放宽到全国最近的省级城市，仅当严格匹配失败时兜底。
pub fn nearest_city_wide(lat: f64, lon: f64) -> Option<(&'static str, f64)> {
    if !(lat.is_finite() && lon.is_finite()) {
        return None;
    }
    if !(17.0..=54.5).contains(&lat) || !(73.0..=135.5).contains(&lon) {
        return None;
    }
    nearest_city(lat, lon, f64::MAX)
}

/// 城市 -> 省份/地区名。
pub fn region_of_city(city: &str) -> &str {
    PROVINCE_OF_CITY
        .iter()
        .find(|(c, _)| *c == city)
        .map(|(_, p)| *p)
        .unwrap_or_else(|| {
            CITIES
                .iter()
                .find(|(c, _, _)| *c == city)
                .map(|(c, _, _)| *c)
                .unwrap_or("")
        })
}

/// 把地点名拆成 (上级地区, 本级)。
///
/// 例如「上高」->（「江西」,「上高」），「北京」->（"",「北京」）。
pub fn place_parts(place: &str) -> (String, String) {
    if place.is_empty() || place == UNKNOWN {
        return (String::new(), UNKNOWN.to_string());
    }
    let parent = PROVINCE_OF_CITY
        .iter()
        .find(|(c, _)| *c == place)
        .map(|(_, p)| *p)
        .unwrap_or("");
    if !parent.is_empty() && parent != place {
        (parent.to_string(), place.to_string())
    } else {
        (String::new(), place.to_string())
    }
}

/// 没有匹配到城市时，用坐标网格作为地点名。
pub fn coord_label(lat: f64, lon: f64) -> String {
    if !(lat.is_finite() && lon.is_finite()) {
        return UNKNOWN.to_string();
    }
    let ns = if lat >= 0.0 { "北纬" } else { "南纬" };
    let ew = if lon >= 0.0 { "东经" } else { "西经" };
    format!("{}{:.1}° {}{:.1}°", ns, lat.abs(), ew, lon.abs())
}

/// 从路径/文件名里找地点线索。
pub fn place_from_text(text: &str) -> Option<&'static str> {
    if text.is_empty() {
        return None;
    }
    let cleaned = noise_re().replace_all(text, " ");
    for name in all_names() {
        if cleaned.contains(*name) {
            return Some(name);
        }
    }
    None
}

/// 只看目录部分（文件名里的「北京」更可能是内容而非地点）。
pub fn place_from_folder(path: &str) -> String {
    let dir = std::path::Path::new(path)
        .parent()
        .map(|p| p.to_string_lossy().to_string())
        .unwrap_or_default();
    place_from_text(&dir)
        .map(|s| s.to_string())
        .unwrap_or_else(|| UNKNOWN.to_string())
}

/// 综合三条线索给出地点名，永远返回一个可分组的值。
///
/// 优先级：目录/文件名里的地名 > GPS 最近城市(60km) > GPS 最近城市(全国) > 未知地点
pub fn resolve_place(lat: Option<f64>, lon: Option<f64>, path_hint: &str) -> String {
    if let Some(named) = place_from_text(path_hint) {
        return named.to_string();
    }
    if let (Some(lat), Some(lon)) = (lat, lon) {
        if let Some((city, _)) = nearest_city(lat, lon, 60.0) {
            return city.to_string();
        }
        if let Some((city, _)) = nearest_city_wide(lat, lon) {
            return city.to_string();
        }
    }
    UNKNOWN.to_string()
}

/// 把坐标翻译成人能读的地区名（用于详情页显示原始定位）。
pub fn describe_coord(lat: Option<f64>, lon: Option<f64>) -> String {
    let (Some(lat), Some(lon)) = (lat, lon) else {
        return String::new();
    };
    let city = nearest_city(lat, lon, 120.0).or_else(|| nearest_city_wide(lat, lon));
    match city {
        Some((c, _)) => format!("{}（{}）", c, region_of_city(c)),
        None => coord_label(lat, lon),
    }
}

