    #[test]
    fn noise_words_do_not_become_places() {
        // 「截图」「微信」这些不该被当成地名
        assert!(place_from_text("屏幕截图 北京").is_some());
        // 但去掉噪词后仍能匹配真实地名
        assert_eq!(place_from_text("微信图片_上海"), Some("上海"));
    }

    #[test]
    fn place_parts_splits_province() {
        assert_eq!(place_parts("上高"), ("江西".to_string(), "上高".to_string()));
        assert_eq!(place_parts("北京"), (String::new(), "北京".to_string()));
        assert_eq!(
            place_parts(UNKNOWN),
            (String::new(), UNKNOWN.to_string())
        );
        assert_eq!(place_parts(""), (String::new(), UNKNOWN.to_string()));
    }

    #[test]
    fn place_from_folder_ignores_filename() {
        assert_eq!(place_from_folder(r"D:\照片\北京\上海之行.jpg"), "北京");
        assert_eq!(place_from_folder(r"D:\照片\a.jpg"), UNKNOWN);
    }

    #[test]
    fn coord_label_formats() {
        assert_eq!(coord_label(39.9, 116.4), "北纬39.9° 东经116.4°");
        assert_eq!(coord_label(-33.9, -70.6), "南纬33.9° 西经70.6°");
        assert_eq!(coord_label(f64::NAN, 0.0), UNKNOWN);
    }

    #[test]
    fn describe_coord_includes_province() {
        let s = describe_coord(Some(28.24), Some(114.92));
        assert!(s.contains("上高"), "{s}");
        assert!(s.contains("江西"), "{s}");
        assert_eq!(describe_coord(None, None), "");
    }

    #[test]
    fn out_of_china_coords_still_work() {
        // 巴黎
        assert_eq!(resolve_place(Some(48.86), Some(2.35), ""), "巴黎");
        // 完全在外太空
        assert_eq!(resolve_place(Some(0.0), Some(0.0), ""), UNKNOWN);
    }

    #[test]
    fn long_names_matched_first() {
        // 「西双版纳」不能被「西双」之类的前缀误匹配
        assert_eq!(place_from_text("西双版纳旅行"), Some("西双版纳"));
    }
